const dictionaries: Record<Language, Record<MessageKey, string>> = { es, en };

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[language][key] ?? es[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

